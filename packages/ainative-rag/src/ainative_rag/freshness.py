"""内容新鲜度感知的缓存键——文档更新/删除后旧缓存必须自然失效。

改造自checklist A类"引用溯源与内容新鲜度子类"真实发现的反面案例（对
`anything-chat-rag`真实代码问答缓存设计提炼）：真实项目的问答缓存键
只由查询内容的哈希构成，不包含任何文档版本/ID关联信息，导致文档删除/
更新后，基于旧内容生成的缓存答案会持续被提供给未来完全不知情的用户，
且缓存键设计上就无法追溯到"这条缓存是从哪份文档衍生的"，删除时也就
无从清理。

正确设计原则：缓存键必须显式包含"参与生成这份答案的每份文档当前的
版本标识"，而不是只哈希查询文本本身——文档版本变化时，同样的查询文本
会自然产生不同的缓存键，旧缓存条目不会被错误复用，也天然具备"按
doc_id关联清理"的能力（不需要额外的删除时清理机制）。
"""

# 什么是"缓存键"（cache key）？为了避免同一个问题被反复计算/反复调用
# 昂贵的模型接口，很多系统会把"问题->答案"存进缓存，下次遇到相同问题
# 直接从缓存里取结果，不用重新计算。"缓存键"就是用来在缓存里定位这份
# 答案的那个唯一标识字符串——通常由请求的内容算出一个哈希值。这个文件
# 要解决的问题是："同样的问题文本，但背后的知识库文档已经更新了"这种
# 情况下，缓存键必须跟着变化，否则会一直返回基于旧文档生成的过时答案。

from __future__ import annotations

# hashlib是Python标准库自带的哈希计算模块——"哈希"（hash）是把任意
# 长度的输入数据，转换成一个固定长度、几乎不可能与其他不同输入撞出
# 相同结果的短字符串（术语叫"摘要"），常用来做"内容指纹"：只要输入
# 内容有一点点不同，算出来的哈希值就会完全不同。
import hashlib

# json是Python标准库自带的JSON序列化模块——用来把Python的字典/列表等
# 数据结构，转换成JSON格式的文本字符串（或反过来解析回来）。
import json


def build_freshness_aware_cache_key(query: str, *, doc_versions: dict[str, str]) -> str:
    """构造缓存键——显式纳入`doc_versions`（`{doc_id: version_or_hash}`），
    而不是只哈希`query`本身。

    Args:
        query: 用户查询文本。
        doc_versions: 参与生成这次回答的每份文档，当前的版本标识（可以是
            版本号、内容哈希、或最后更新时间戳，只要文档内容变化时这个
            值也会变化）。按key排序后参与哈希计算，保证"同一组文档、
            不同顺序传入"仍然产生相同的缓存键。

    Returns:
        一个稳定的缓存键字符串——`query`不变但任意一份`doc_versions`
        变化，都会产生不同的键，天然让旧缓存失效，不需要额外的删除时
        清理机制。

    真实bug背景：早期实现用`"|".join(f"{k}:{v}")`这类手工拼接分隔符的
    方式构造哈希输入，如果`doc_id`或版本值本身含有`:`/`|`这类分隔符
    字符（真实场景下doc_id经常是路径/哈希/带命名空间的字符串，并不罕见），
    两组完全不同的`doc_versions`会拼接出一模一样的字符串，产生哈希碰撞——
    比如`{"a": "1", "b": "2"}`和`{"a": "1|b:2"}`会拼出相同的`"a:1|b:2"`。
    改用`json.dumps`结构化序列化：JSON会给每个字符串正确加引号/转义，
    `"a:b"`和`"a"`在JSON里永远是两个不同的token，不可能因为内容恰好
    包含分隔符字符就被混淆成同一个序列化结果。
    """
    # 参数列表里单独的`*`，表示它后面的`doc_versions`必须用"参数名=值"
    # 的方式传入（`build_freshness_aware_cache_key(q, doc_versions={...})`），
    # 不能只按位置传参——强制调用方把这个参数名写出来，代码本身自带
    # 说明性，不容易和`query`搞混谁是谁。

    payload = json.dumps({"query": query, "doc_versions": doc_versions}, sort_keys=True, ensure_ascii=False)
    # ↑ 这一行是本模块修复的那处真实bug的核心：不再用手工拼接分隔符
    #   字符串的方式构造哈希输入，而是先把"查询文本+文档版本字典"打包
    #   成一个普通的Python字典，再用`json.dumps(...)`把它序列化成一段
    #   JSON格式的文本。几个关键参数：
    #   - `sort_keys=True`：JSON序列化时，把字典的key按字母顺序排好序
    #     再输出——这保证了`{"a": "1", "b": "2"}`和`{"b": "2", "a": "1"}`
    #     这种"内容相同、只是Python字典构造时传入顺序不同"的输入，
    #     序列化出来的JSON文本是完全一样的字符串（Python字典本身从
    #     3.7起会记住插入顺序，如果不显式排序，两种传参顺序会产出
    #     不同的JSON文本，进而算出不同的哈希，明明代表同一组文档却
    #     被当成了不同的缓存键，这是需要避免的）。
    #   - `ensure_ascii=False`：允许JSON里直接保留中文等非ASCII字符
    #     本身的样子，不转成`\uXXXX`这种转义序列——不影响正确性（两种
    #     写法对不同输入依然会得到不同字符串），只是让中间产物更易读。
    #   JSON格式天然会给每个字符串值加上引号、并对字符串内部出现的
    #   特殊字符（包括`:`和`|`）做转义处理，所以`{"a": "1|b:2"}`和
    #   `{"a": "1", "b": "2"}`序列化出来的JSON文本必然不同，不会像
    #   旧版手工拼接那样意外拼出一模一样的字符串。
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()
    # ↑ `payload.encode("utf-8")`：把上一步得到的JSON字符串转换成字节
    #   序列（哈希函数处理的是字节，不是Python的字符串对象，这一步是
    #   必要的类型转换）。`hashlib.sha256(...)`用SHA-256算法对这些
    #   字节计算哈希；`.hexdigest()`把计算结果转换成一段固定长度（64个
    #   字符）的十六进制字符串，就是最终返回的缓存键——只要`query`或
    #   `doc_versions`任何一处内容不同，这个字符串几乎必然完全不同。
