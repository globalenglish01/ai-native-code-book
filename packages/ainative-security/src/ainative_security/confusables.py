"""同形字（homoglyph）攻击字符集 + 精确折叠。

背景：攻击者用视觉上与拉丁字母几乎无法区分的西里尔/希腊字母改写注入关键词
（如西里尔"а" U+0430冒充拉丁"a" U+0061，把"ignore"写成"ignоre"绕过正则）。

关键事实：NFKC归一化**并不**把西里尔/希腊同形字折叠成拉丁字母（它们不是
Unicode兼容等价字符），所以"全量NFKC"路径对这类攻击其实零防护，反而会误伤
合法的全角字符（比如面向日文市场的产品，全角是合法业务内容）。

本模块只对**已知有攻击价值的精确字符集**（拉丁形近的西里尔/希腊字母）做折叠，
**绝不触碰全角字符**（全角数字/标点/假名不在此表内，折叠后原样保留）。

维护：`CONFUSABLES`是可持续扩充的映射表，安全团队发现新攻击样本时按
(混淆字符 → ASCII等价)追加即可，无需改动检测逻辑。数据源参考Unicode
Consortium confusables.txt中Cyrillic/Greek → Latin的子集。
"""

# 先解释一下这个文件到底在防什么：每一个字符在计算机内部，最终都是一个
# 数字编号（这套编号规则叫Unicode，几乎覆盖了世界上所有文字）。问题是，
# 有些不同文字体系里的字符，编号完全不同，但画出来的"字形"却长得几乎
# 一模一样——比如英文字母小写"a"（Unicode编号是97，也就是常说的
# U+0061）和西里尔字母（俄语等斯拉夫语言用的字母表）里的一个字母
# （编号是1072，即U+0430），肉眼几乎分辨不出区别，但对电脑/正则表达式
# 来说，它们是彻头彻尾两个不同的字符。攻击者可以利用这一点，把英文单词
# "ignore"里的字母"o"，偷偷换成那个长得像"o"、实际是西里尔字母的字符，
# 这样"检测是否包含ignore这个词"的正则表达式就会完全匹配失败（因为
# 严格按字符编号比较，两者根本不相等），但人眼看着这段文字，完全看不出
# 任何异常——这就是"同形字攻击"（homoglyph attack），也叫"混淆字符"
# （confusable characters）攻击。本文件要做的事，就是提前把这些"看起来
# 像拉丁字母、实际是别的文字"的字符，统一换成它们冒充的那个真正的拉丁
# 字母，这样后续检测注入关键词的正则表达式才能正常发挥作用。

from __future__ import annotations

# 这是一个字典（dict）——Python里"键(key) → 值(value)"的映射结构，写法
# 是 `{key1: value1, key2: value2, ...}`。这里的key是"容易被拿来冒充
# 拉丁字母的西里尔/希腊字符"，value是它对应冒充的那个真正拉丁字母。
# 下面按字母表来源分成四组，用`# ── 标题 ──`这种注释仅仅是给人看的
# 分节标题，不影响程序运行。
CONFUSABLES: dict[str, str] = {
    # ── 西里尔小写 → 拉丁 ──
    "а": "a", "е": "e", "о": "o", "р": "p", "с": "c", "у": "y", "х": "x",
    "ѕ": "s", "і": "i", "ј": "j", "һ": "h", "ԁ": "d", "ԛ": "q", "ԝ": "w",
    "к": "k", "в": "b", "м": "m", "н": "h", "т": "t",
    # ── 西里尔大写 → 拉丁 ──
    "А": "A", "В": "B", "Е": "E", "К": "K", "М": "M",
    "Н": "H", "О": "O", "Р": "P", "С": "C", "Т": "T",
    "У": "Y", "Х": "X", "І": "I", "Ј": "J", "Ѕ": "S",
    # ── 希腊小写 → 拉丁 ──
    "ο": "o", "α": "a", "ρ": "p", "υ": "u", "ν": "v", "χ": "x", "κ": "k",
    # ── 希腊大写 → 拉丁 ──
    "Α": "A", "Β": "B", "Ε": "E", "Ζ": "Z", "Η": "H",
    "Ι": "I", "Κ": "K", "Μ": "M", "Ν": "N", "Ο": "O",
    "Ρ": "P", "Τ": "T", "Υ": "Y", "Χ": "X",
}

# 这一行是一个"字典推导式"（dict comprehension）——一种用一行代码，从
# 一个已有的集合，快速构造出一个新字典的写法，格式是
# `{key表达式: value表达式 for 变量 in 可迭代对象}`。这里的意思是：
# 遍历上面`CONFUSABLES`字典里的每一对(k, v)，对每一对，
# 用`ord(k)`把字符k转换成它的Unicode编号（数字），作为新字典的key，
# 原来的替换目标字符v保持不变作为新字典的value。
# 为什么要多此一举转换成数字编号？因为Python字符串内置的`.translate()`
# 方法（下面`fold_confusables`会用到）要求的转换表，key必须是Unicode
# 编号（整数），不能直接是字符本身，所以这里提前做好这层转换，避免每次
# 调用`fold_confusables`时都重新计算一遍。
_TRANSLATE_TABLE = {ord(k): v for k, v in CONFUSABLES.items()}


def has_confusables(text: str) -> bool:
    """text是否含已知攻击同形字。"""
    # `any(条件 for c in text)` 的意思是"遍历text这个字符串里的每一个
    # 字符c，只要有任意一个字符满足后面的条件，就整体返回True；如果
    # 一个都不满足，返回False"（这叫"生成器表达式"，是一种边遍历边
    # 判断、不需要提前把所有结果都存成一个列表的写法，性能更好）。
    # 这里的条件是`ord(c) in _TRANSLATE_TABLE`——把当前字符c转换成它的
    # Unicode编号，检查这个编号是不是在我们准备好的"已知攻击字符"转换表
    # 的key集合里。
    return any(ord(c) in _TRANSLATE_TABLE for c in text)


def fold_confusables(text: str) -> str:
    """只把已知攻击同形字折叠成ASCII等价字符，其余字符（含全角字符）原样保留。"""
    # 空字符串（或None，虽然类型注解说只应该传字符串）直接原样返回，
    # 没必要走一遍下面的转换逻辑。
    if not text:
        return text
    # `.translate(表)` 是Python字符串的内置方法：它会遍历text里的每一个
    # 字符，查一下这个字符的Unicode编号在不在传入的转换表里——在的话，
    # 就把这个字符替换成表里对应的那个字符；不在的话，这个字符原样保留、
    # 不做任何改动。这正好符合本模块开头强调的设计原则："只折叠已知的
    # 攻击字符，其余一切（包括合法的全角字符）都不碰"。
    return text.translate(_TRANSLATE_TABLE)
