"""对话内容持久化前的轻量PII检测/脱敏（规则匹配版）。

设计原则：
1. **绝不抛异常**：检测/脱敏本身出问题绝不能拖垮上层的持久化/对话流程。
2. **保留业务可读性**：脱敏时只涂黑中间部分，保留能辨认"这是身份证/手机号"
   的首尾片段，不是整段删除或替换成不透明的占位符。
3. **只提供纯函数，不关心调用时机**：本模块自身不假设自己会在什么时候被调用
   （比如checkpoint写入前、日志记录前、summarization溢出到历史文件前）——
   由使用方在自己的持久化/日志管道里决定何时调用`redact_pii_text`。

**当前覆盖范围**（第一阶段，规则匹配）：
- 中国大陆身份证号（18位，末位可为X/x校验位）
- 中国大陆手机号（11位，1[3-9]开头）

**明确未覆盖、留待后续评估**：人名、地址、银行卡号等无固定格式规律、需要
上下文理解才能识别的PII类型，通常需要专门的NER模型/服务，超出"规则匹配"
这个第一阶段的范围。
"""

# PII是"Personally Identifiable Information"（个人身份信息）的缩写——
# 泛指身份证号、手机号、银行卡号等一旦泄露就能定位到具体某个人的信息。
# "脱敏"（redact）指的是把这类敏感信息的一部分替换/遮盖掉，让保存下来的
# 日志/对话记录既能保留业务可读性（还能看出"这是一条身份证号"），又不会
# 完整暴露真实号码。

from __future__ import annotations

# re是Python标准库里处理"正则表达式"（regular expression，简称regex）的
# 模块。正则表达式是一种专门描述"字符串长什么样子"的迷你语言——比如
# "连续11个数字，且第一个是1"这种规则，写成人类语言很啰嗦，但用正则表达式
# 可以写成一小段紧凑的模式，交给`re`模块去自动匹配、查找、替换。本文件
# 后面出现的两个正则表达式都是在描述"身份证号/手机号长什么样"。
import re

__all__ = ["COVERED_PII_TYPES", "redact_pii_text"]

# 一个"元组"（tuple，小括号包起来、创建后不能修改的一组值），列出目前
# 这个模块实际支持检测的PII类型名字——方便调用方/文档知道"目前覆盖到
# 什么程度"，不需要去读正则表达式本身才能知道。
COVERED_PII_TYPES: tuple[str, ...] = ("china_id_card", "china_mobile_phone")

# 中国大陆身份证号：18位，前17位数字，末位数字或X/x（校验位）。
# 用前后向零宽断言避免匹配到更长数字串的子串（而不是\b——Python re把CJK
# 表意文字也算作\w，紧邻中文字符时\b不产生边界，会导致"号是310101...1234"
# 这类前面紧跟中文字符的真实场景漏检）；不做行政区划码/出生日期的合法性
# 校验（规则匹配阶段的定位是"高召回、可接受一定误报"，不是精确身份证校验器）。
#
# 下面这行`re.compile(...)`的作用是"提前把这段正则表达式的文字描述，
# 编译成一个可以反复高效使用的Pattern对象"——如果不用compile，每次调用
# `redact_pii_text`时都要重新解析一遍正则表达式文字，效率更低；`compile`
# 一次、之后反复调用`.sub()`/`.search()`是常见的性能最佳实践。
#
# 这段正则具体在描述什么，逐段翻译成人话：
#   (?<!\d)      —— "前面不能紧跟着一个数字"（这叫"负向前瞻的反向版本"，
#                    术语叫"零宽负向后顾断言"，"零宽"是说它自己不占字符
#                    位置，只是"往前看一眼、不满足就不算匹配"，不会被
#                    包含进最终匹配到的字符串里）。作用：避免把一个19位
#                    数字串的中间/末尾18位误判成一个独立的身份证号。
#   \d{17}       —— 连续17个数字（\d就是"任意一个数字字符0-9"的简写，
#                    {17}表示"重复17次"）。
#   [\dXx]       —— 第18位：可以是数字，也可以是大写或小写的字母X
#                    （身份证号最后一位是"校验位"，按国家标准算法算出来，
#                    结果有时候刚好是罗马数字X，代表10）。
#   (?![\dXx])   —— "后面不能紧跟着另一个数字或X/x"（"零宽负向前瞻断言"，
#                    和前面`(?<!\d)`是同一个思路，只是方向相反：往后看
#                    一眼）。作用：避免把一个19位数字+X的串误判成"前18位
#                    是身份证号"。
_CHINA_ID_CARD_RE = re.compile(r"(?<!\d)\d{17}[\dXx](?![\dXx])")

# 中国大陆手机号：11位，1[3-9]开头。同样用零宽断言而非\b（理由同上）。
# 翻译：(?<!\d) 前面不能是数字；1 第一位必须是数字1；[3-9] 第二位必须是
# 3到9之间的某一个数字（中国大陆手机号号段固定以1开头、第二位在这个
# 范围内）；\d{9} 后面再跟9个任意数字（凑够总共11位）；(?!\d) 后面不能
# 再紧跟一个数字，避免匹配到更长数字串里的一段。
_CHINA_MOBILE_RE = re.compile(r"(?<!\d)1[3-9]\d{9}(?!\d)")


def _mask_id_card(m: re.Match[str]) -> str:
    """保留前6位（地区码）+后4位，中间8位掩码——与国内常见的身份证脱敏惯例一致。"""
    # 这个函数的参数`m`是一个`re.Match`对象——每当正则表达式在文本里
    # 成功匹配到一处，`re`模块就会生成这样一个对象，装着"具体匹配到了
    # 哪一段文字、在原文的什么位置"等信息。这个函数会被作为"替换规则"
    # 传给下面`redact_pii_text`里的`.sub(函数, 文本)`调用——`.sub()`
    # 每找到一处匹配，就会把匹配到的这个`Match`对象传给这个函数，函数
    # 返回的字符串会被用来替换掉原文里匹配到的那一段。
    # `m.group(0)` 表示"取出这次匹配到的完整字符串"（0号分组永远代表
    # 整个匹配结果本身，不是某个用括号圈出来的子部分——这里的正则表达式
    # 也确实没有用括号定义任何子分组）。
    s = m.group(0)
    # 字符串切片`s[:6]`表示"从开头取6个字符"，`s[-4:]`表示"从倒数第4个
    # 字符开始取到最后"——这样就拿到了身份证号的前6位（地区码）和后4位，
    # f-string（`f"..."`）里的`{}`会被自动替换成对应变量的值，中间用
    # 8个星号占位，掩盖真正的18位号码中间那一段。
    return f"{s[:6]}********{s[-4:]}"


def _mask_mobile(m: re.Match[str]) -> str:
    """保留前3位（运营商号段）+后4位，中间4位掩码——如 138****1234。"""
    s = m.group(0)
    return f"{s[:3]}****{s[-4:]}"


def redact_pii_text(text: str) -> str:
    """对单段文本做PII脱敏。绝不抛异常——异常时原样返回，宁可漏检也不中断调用方流程。

    幂等：对已经脱敏过的文本再跑一次是安全的（掩码后的字符串不会再匹配身份证/手机号
    的格式规则），"已脱敏的旧内容 + 新内容"拼接后整体传入时不会造成重复脱敏或内容损坏。
    """
    # 双重防御：`not text`会在text是None、空字符串这类"假值"时触发；
    # `not isinstance(text, str)`额外防住"调用方传进来的根本不是字符串"
    # 这种情况（比如不小心传了个数字或None以外的其他类型）。任何一个
    # 条件成立，就直接原样把text返回，不做任何处理——这是"绝不抛异常"
    # 这个设计原则最前面的一道防线。
    if not text or not isinstance(text, str):
        return text
    # try/except：先尝试执行下面这两行替换逻辑，如果过程中因为任何原因
    # 抛出了异常（哪怕是完全没预料到的类型），都会被下面的except接住，
    # 不会导致调用这个函数的上层代码跟着崩溃。
    try:
        # `.sub(替换函数, 原文本)` 是正则Pattern对象的方法：在原文本里
        # 找到所有匹配这个正则的地方，每找到一处，就调用一次传入的替换
        # 函数（这里是上面定义的`_mask_id_card`），并用函数的返回值
        # 替换掉原文里那一处匹配到的文字，最终返回替换完成后的新字符串。
        text = _CHINA_ID_CARD_RE.sub(_mask_id_card, text)
        text = _CHINA_MOBILE_RE.sub(_mask_mobile, text)
    except Exception:  # noqa: BLE001
        # 这一行末尾的特殊注释是给代码检查工具（ruff）看的："noqa"后面跟着
        # 的代号，意思是"这里刻意捕获了范围很宽泛的Exception（几乎所有
        # 异常都会被接住），请检查工具不要为此报警告"——因为这正是"绝不
        # 抛异常"这个设计原则
        # 要求的效果：不管出了什么类型的错，都不能让这个函数把异常继续
        # 往外抛。出问题时就返回原始未处理的文本，接受"这次可能没脱敏
        # 成功"的代价，也不让上层的持久化/对话流程被中断。
        return text
    return text
